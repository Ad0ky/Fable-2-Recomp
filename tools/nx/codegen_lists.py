#!/usr/bin/env python3
"""fable2-nx on renut_nx_ultimate_base: the register-diet audits of the base (docs/katamari-notes.md "Codegen options:
the register diet"), done by the Docker build after every code generation and written into the codegen config, so the
next code generation takes them. Both lists only grow (an address once listed stays; delete the file to start again).

  share <gen> : tools/read_before_write.py on code generated WITH non_volatile_as_local (app/generated, before the
                post-codegen passes). Every function that reads a non-volatile register its parent set up (a split
                piece, a __finally funclet called with the parent's frame in r31) is marked share_registers in
                app/config/fable2_share_registers.toml: its whole [functions] entry (name and size from
                config/fable2_funcs.toml), included after that file so it wins. Left out: functions whose only such
                reads are of condition fields (mfcr saving the whole CR, setjmp saving CR / XER: values only stored).
  keep <gen>  : tools/non_argument_audit.py on code generated WITHOUT non_argument_as_local (out/audit/gen_noarg, from
                app/audit_noarg_manifest.toml). Every ENTRY and RET function goes into non_argument_as_local_keep in
                app/config/fable2_audit.toml (katamari-nx kept all of its 6,379 the same way).
Exit status 0; prints how many addresses each list gained ("NEW n": the build generates the code again when n > 0).
"""
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CFG = os.path.join(ROOT, 'app', 'config')
FUNCS = os.path.join(CFG, 'fable2_funcs.toml')
SHARE = os.path.join(CFG, 'fable2_share_registers.toml')
AUDIT = os.path.join(CFG, 'fable2_audit.toml')
NORETURN = '--noreturn=82CA9260'  # Fable 2's longjmp
ADDR = re.compile(r'([0-9A-Fa-f]{8})$')


def funcs_by_name():
    by_name, by_addr = {}, {}
    cur = None
    for line in open(FUNCS, encoding='utf-8'):
        m = re.match(r'^\[functions\."0x([0-9A-Fa-f]{8})"\]', line)
        if m:
            cur = int(m.group(1), 16)
            by_addr[cur] = []
            continue
        if line.startswith('['):
            cur = None
            continue
        if cur is not None and re.match(r'^\s*(name|size|end|parent)\s*=', line):
            by_addr[cur].append(line.strip())
            n = re.match(r'^\s*name\s*=\s*"([^"]+)"', line)
            if n:
                by_name[n.group(1)] = cur
    return by_name, by_addr


def address_of(name, by_name):
    if name in by_name:
        return by_name[name]
    m = ADDR.search(name)
    return int(m.group(1), 16) if m else None


def existing(path, pattern):
    if not os.path.isfile(path):
        return set()
    return {int(x, 16) for x in re.findall(pattern, open(path, encoding='utf-8').read())}


def processed(gen):
    """True when the tree has been through tools/post_codegen.py (the audits read only the generator's own text)."""
    import glob
    for f in sorted(glob.glob(os.path.join(gen, '*_recomp.*.cpp')))[:3]:
        text = open(f, encoding='utf-8', errors='ignore').read()
        if 'REX_DEAD_SAVE(' in text or 'REX_DEAD_DEF(' in text or 'REX_STORE_CARD' in text:
            return True
    return False


def share(gen):
    if processed(gen):
        sys.exit(f'share: {gen} has been through the post-codegen passes; the audit needs a fresh code generation')
    by_name, by_addr = funcs_by_name()
    out = subprocess.run([sys.executable, os.path.join(ROOT, 'tools', 'read_before_write.py'), gen, NORETURN],
                         capture_output=True, text=True, cwd=ROOT)
    os.makedirs(os.path.join(ROOT, 'out', 'audit'), exist_ok=True)
    open(os.path.join(ROOT, 'out', 'audit', 'share_raw.txt'), 'w').write(out.stdout + out.stderr)
    found = {}
    for line in out.stdout.splitlines():
        if line.startswith('#') or ' | ' not in line:
            continue
        head, why = line.split(' | ', 1)
        parts = head.split()
        name, regs = parts[0], parts[1:]
        if all(r.startswith('cr') or r == 'xer' for r in regs):
            continue
        a = address_of(name, by_name)
        if a is None:
            print(f'share: no address for {name} ({" ".join(regs)}), left out')
            continue
        found[a] = (name, regs, why[:90])
    old = existing(SHARE, r'\[functions\."0x([0-9A-Fa-f]{8})"\]')
    new = set(found) - old
    allv = old | set(found)
    lines = ['# fable2-nx: generated by tools/nx/codegen_lists.py share (tools/read_before_write.py on code generated with',
             '# non_volatile_as_local): the functions that read non-volatile registers their parent set up. Each entry keeps',
             '# its name and size from fable2_funcs.toml (this file is included after it and replaces the whole entry).', '']
    prev = {}
    if os.path.isfile(SHARE):
        for m in re.finditer(r'\[functions\."0x([0-9A-Fa-f]{8})"\]\n((?:[^\[\n].*\n)*)', open(SHARE, encoding='utf-8').read()):
            prev[int(m.group(1), 16)] = m.group(2)
    for a in sorted(allv):
        lines.append(f'[functions."0x{a:08X}"]')
        if a in found:
            name, regs, why = found[a]
            lines.append(f'# {name}: {" ".join(regs)} | {why}'.replace('\n', ' '))
        elif a in prev:
            lines.extend(l for l in prev[a].splitlines() if l.startswith('#'))
        lines.extend(by_addr.get(a, []))
        lines.append('share_registers = true')
        lines.append('')
    open(SHARE, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    print(f'share: {len(found)} functions read non-volatiles their parent set up; {len(allv)} listed; NEW {len(new)}')


def keep(gen):
    if processed(gen):
        sys.exit(f'keep: {gen} has been through the post-codegen passes; the audit needs a fresh code generation')
    by_name, _ = funcs_by_name()
    out = subprocess.run([sys.executable, os.path.join(ROOT, 'tools', 'non_argument_audit.py'), gen, NORETURN],
                         capture_output=True, text=True, cwd=ROOT)
    os.makedirs(os.path.join(ROOT, 'out', 'audit'), exist_ok=True)
    open(os.path.join(ROOT, 'out', 'audit', 'keep_raw.txt'), 'w').write(out.stdout + out.stderr)
    if out.returncode != 0:
        print(out.stderr[-3000:])
        sys.exit('keep: non_argument_audit.py failed')
    found = set()
    for line in out.stdout.splitlines():
        m = re.match(r'^(ENTRY|RET) (\S+)', line)
        if not m:
            continue
        a = address_of(m.group(2), by_name)
        if a is None:
            print(f'keep: no address for {m.group(2)}, left out')
            continue
        found.add(a)
    old = existing(AUDIT, r'0x([0-9A-Fa-f]{8})')
    allv = sorted(old | found)
    body = ',\n'.join('    ' + ', '.join(f'0x{a:08X}' for a in allv[i:i + 8]) for i in range(0, len(allv), 8))
    text = ('# fable2-nx: generated by tools/nx/codegen_lists.py keep (tools/non_argument_audit.py on code generated without\n'
            '# non_argument_as_local): the functions that take or return a value in r0/r2/r11/r12/f0/v32-v63 (save / restore\n'
            '# helpers, MSVC funclets, ...). They keep those registers in ctx; their callers hand them over.\n'
            'non_argument_as_local_keep = [\n' + body + ('\n' if body else '') + ']\n')
    open(AUDIT, 'w', encoding='utf-8').write(text)
    print(f'keep: {len(found)} ENTRY / RET functions; {len(allv)} listed; NEW {len(set(found) - old)}')


if __name__ == '__main__':
    {'share': share, 'keep': keep}[sys.argv[1]](sys.argv[2])
